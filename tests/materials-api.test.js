import assert from 'node:assert/strict';
import { test } from 'node:test';
import { createHash } from 'node:crypto';
import { createWebServer } from '../src/web/server.js';
import { webConfig } from './fixtures/web-config.js';

const fetchWithPassword = (url, options = {}) => globalThis.fetch(url, {
  ...options, headers: { ...options.headers },
});

async function server(t, configFile, workflow) {
  const app = createWebServer({ port: 0, configFile, workflow,
    users: [{ username: 'fixture', password: 'fixture-pass' }] });
  const origin = await app.start();
  t.after(() => app.close());
  const login = await globalThis.fetch(`${origin}/api/login`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ username: 'fixture', password: 'fixture-pass' }),
  });
  assert.equal(login.status, 200);
  const session = await login.json();
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const request = (path, options = {}) => fetchWithPassword(`${origin}${path}`, {
    ...options, headers: { Cookie: cookie, 'X-Local-Token': session.token, ...options.headers },
  });
  return { app, origin, request };
}

const url = id => `https://services.sheerid.com/verify/aaaaaaaaaaaaaaaaaaaaaaaa/?verificationId=${id}`;

test('A submitted task generates, archives and serves US material', async t => {
  const { configFile } = await webConfig(t);
  const { app, request } = await server(t, configFile, async () => ({ status: 'verified', code: 'STEP_RECEIVED' }));
  const verificationId = 'eeeeeeeeeeeeeeeeeeeeeeee';
  const started = await request('/api/jobs', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    // Only a URL: identity, birth date and documents are generated by the system.
    body: JSON.stringify({ url: url(verificationId) }),
  });
  assert.equal(started.status, 202);
  const { job } = await started.json();
  assert.match(job.id, /^[a-f\d]{24}$/);
  assert.notEqual(job.id, verificationId);
  assert.ok(job.material, 'the queue snapshot carries the generated material');
  assert.equal(job.material.source, 'generated');
  assert.equal(job.material.taskId, job.id);
  assert.equal(job.material.sheeridVerificationId, verificationId);
  assert.match(job.material.identity.email, /@[a-z0-9.-]+\.edu$/);
  assert.match(job.material.identity.birthDate, /^\d{4}-\d{2}-\d{2}$/);
  assert.ok(job.material.identity.studentNumber.length >= 6);
  assert.match(job.material.university.name, /University|Institute|College/);
  await app.jobs.jobs.get(job.id).done;

  const list = await (await request('/api/materials')).json();
  assert.equal(list.materials.length, 1);
  assert.equal(list.materials[0].verificationId, job.id);
  assert.equal(list.materials[0].taskId, job.id);
  assert.equal(list.materials[0].sheeridVerificationId, verificationId);
  assert.equal(list.materials[0].url, url(verificationId));
  assert.equal(list.materials[0].task.profile, 'google-one');
  assert.equal(list.materials[0].task.proxyProvider, 'configured');
  assert.ok(list.materials[0].task.submittedAt);

  const detail = await (await request(`/api/materials/${job.id}`)).json();
  assert.equal(detail.material.identity.studentNumber, job.material.identity.studentNumber);
  // Enrollment certificate + term verification (the portrait card is not generated).
  assert.equal(detail.material.files.length, 2);
  assert.equal(detail.material.lastStatus, 'verified');

  const file = await request(`/api/materials/${job.id}/files/enrollment-certificate.pdf`);
  assert.equal(file.status, 200);
  assert.equal(file.headers.get('content-type'), 'application/pdf');
  const bytes = Buffer.from(await file.arrayBuffer());
  assert.equal(bytes.subarray(0, 8).toString('latin1'), '%PDF-1.7');
  const entry = detail.material.files.find(item => item.name === 'enrollment-certificate.pdf');
  assert.equal(createHash('sha256').update(bytes).digest('hex'), entry.sha256);

  // Unknown ids and traversal attempts are rejected without touching the filesystem.
  assert.equal((await request('/api/materials/ffffffffffffffffffffffff')).status, 404);
  assert.equal((await request(`/api/materials/${job.id}/files/..%2Fmaterial.json`)).status, 404);
  assert.equal((await request(`/api/materials/${job.id}/files/unknown.pdf`)).status, 404);

  const universities = await (await request('/api/universities')).json();
  assert.ok(universities.universities.length >= 10);
  assert.ok(universities.universities.some(entry => entry.id === 'mit' && entry.emailDomain === 'mit.edu'));
});

test('Re-submitting the same verificationId assigns a new random taskId and keeps separate archive records', async t => {
  const { configFile } = await webConfig(t);
  const verificationId = 'ffffffffffffffffffffffff';
  const first = await server(t, configFile, async () => ({ status: 'pending' }));
  const started = await first.request('/api/jobs', {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ url: url(verificationId) }),
  });
  const { job } = await started.json();
  await first.app.jobs.jobs.get(job.id).done;
  const studentNumber = job.material.identity.studentNumber;

  const second = await server(t, configFile, async () => ({ status: 'pending' }));
  const rejectedReuse = await second.request('/api/jobs', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ url: url(verificationId), reuseMaterials: true }),
  });
  assert.equal(rejectedReuse.status, 400);

  const again = await second.request('/api/jobs', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ url: url(verificationId) }),
  });
  assert.equal(again.status, 202);
  const fresh = (await again.json()).job;
  assert.notEqual(fresh.id, job.id, 'resubmission gets its own random taskId');
  assert.equal(fresh.material.source, 'generated');
  assert.equal(fresh.material.sheeridVerificationId, verificationId);
  assert.notEqual(fresh.material.identity.studentNumber, studentNumber);
  await second.app.jobs.jobs.get(fresh.id).done;

  const materials = await (await second.request('/api/materials')).json();
  assert.equal(materials.materials.length, 2, 'each submission retains its own independent archive record');
  assert.ok(materials.materials.every(entry => entry.sheeridVerificationId === verificationId));
});

test('University list is filtered by ?country= and defaults to US', async t => {
  const { configFile } = await webConfig(t);
  const { request } = await server(t, configFile, async () => ({ status: 'verified' }));
  const defaults = await (await request('/api/universities')).json();
  assert.ok(defaults.universities.some(entry => entry.id === 'mit'), 'defaults to US dataset');
  assert.ok(!defaults.universities.some(entry => entry.id === 'utoronto'), 'no CA schools in default');

  const ca = await (await request('/api/universities?country=CA')).json();
  assert.ok(ca.universities.some(entry => entry.id === 'utoronto' || entry.id === 'ubc' || entry.id === 'mcgill'), 'CA dataset returned');
  assert.ok(!ca.universities.some(entry => entry.id === 'mit'), 'no US schools in CA dataset');

  const gb = await (await request('/api/universities?country=gb')).json();
  assert.ok(gb.universities.some(entry => entry.id === 'oxford' || entry.id === 'cambridge'), 'GB dataset returned');

  const de = await (await request('/api/universities?country=DE')).json();
  assert.ok(de.universities.length >= 35, 'DE dataset returned');
});

test('Submitted countryCode selects the matching country material', async t => {
  const { configFile } = await webConfig(t);
  const { app, request } = await server(t, configFile, async () => ({ status: 'verified', code: 'STEP_RECEIVED' }));
  const verificationId = 'aaaaaaaaaaaaaaaaaaaaaaaa';
  const started = await request('/api/jobs', {
    method: 'POST', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ url: url(verificationId), countryCode: 'CA' }),
  });
  assert.equal(started.status, 202);
  const { job } = await started.json();
  assert.equal(job.material.university.countryCode, 'CA');
  assert.equal(job.material.university.country, 'Canada');
  assert.match(job.material.identity.email, /@(student\.ubc\.ca|mail\.utoronto\.ca|mail\.mcgill\.ca|uwaterloo\.ca|ualberta\.ca|mcmaster\.ca|uottawa\.ca|queensu\.ca|uwo\.ca|ucalgary\.ca|dal\.ca|sfu\.ca|yorku\.ca|umontreal\.ca|umanitoba\.ca|carleton\.ca)$/);
  assert.match(job.material.identity.address.postalCode, /^[A-Z]\d[A-Z] \d[A-Z]\d$/, 'Canadian postal code');
  await app.jobs.jobs.get(job.id).done;
});
